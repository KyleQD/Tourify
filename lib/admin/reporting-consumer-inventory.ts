/**
 * REP-101 — Inventory of admin reporting consumers (dashboard/card/chart/export/query).
 * Each consumer documents source, formula, org filter, failure, owner, replacement, retirement.
 */

export type ReportingConsumerKind =
  | 'dashboard'
  | 'card'
  | 'chart'
  | 'export'
  | 'query'
  | 'widget'

export type ReportingOrgFilter = 'yes' | 'partial' | 'no' | 'n/a'

export type ReportingFailureBehavior =
  | 'empty'
  | 'error'
  | 'mock'
  | 'degraded'
  | 'unknown'

export type ReportingRetirementPlan =
  | 'keep'
  | 'replace'
  | 'retire'
  | 'consolidate'

export interface ReportingConsumer {
  id: string
  kind: ReportingConsumerKind
  surface: string
  source: string
  formula: string
  orgFilter: ReportingOrgFilter
  failureBehavior: ReportingFailureBehavior
  owner: string
  canonicalReplacement: string
  retirementPlan: ReportingRetirementPlan
  /** Zero-mock policy violation or other risk */
  notes?: string
}

