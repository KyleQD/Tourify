export const REPORTING_REQUIRED_KINDS: ReportingConsumerKind[] = [
  'dashboard',
  'card',
  'chart',
  'export',
  'query',
  'widget',
]

export function listZeroMockViolations(
  consumers: ReportingConsumer[] = REPORTING_CONSUMERS,
): ReportingConsumer[] {
  return consumers.filter(
    (c) =>
      c.failureBehavior === 'mock'
      || (c.notes || '').toUpperCase().includes('ZERO-MOCK'),
  )
}

export function assertRep101InventoryCoverage(
  consumers: ReportingConsumer[] = REPORTING_CONSUMERS,
): { ok: boolean; failures: string[] } {
  const failures: string[] = []
  const ids = new Set<string>()

  for (const c of consumers) {
    if (!c.id) failures.push('consumer missing id')
    if (ids.has(c.id)) failures.push(`duplicate id ${c.id}`)
    ids.add(c.id)
    if (!c.surface?.trim()) failures.push(`${c.id} missing surface`)
    if (!c.source?.trim()) failures.push(`${c.id} missing source`)
    if (!c.formula?.trim()) failures.push(`${c.id} missing formula`)
    if (!c.orgFilter) failures.push(`${c.id} missing orgFilter`)
    if (!c.failureBehavior) failures.push(`${c.id} missing failureBehavior`)
    if (!c.owner?.trim()) failures.push(`${c.id} missing owner`)
    if (!c.canonicalReplacement?.trim()) failures.push(`${c.id} missing canonicalReplacement`)
    if (!c.retirementPlan) failures.push(`${c.id} missing retirementPlan`)
  }

  for (const kind of REPORTING_REQUIRED_KINDS) {
    if (!consumers.some((c) => c.kind === kind))
      failures.push(`no consumer of kind ${kind}`)
  }

  if (listZeroMockViolations(consumers).length === 0)
    failures.push('expected at least one documented zero-mock violation for retirement tracking')

  if (!consumers.some((c) => c.orgFilter === 'no'))
    failures.push('expected at least one unscoped consumer documented (e.g. top-performers)')

  return { ok: failures.length === 0, failures }
}
